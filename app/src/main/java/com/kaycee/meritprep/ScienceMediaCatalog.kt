package com.kaycee.meritprep

enum class ScienceMediaType { ANIMATION, INTERACTIVE_SIMULATION, VIRTUAL_LAB, VIDEO, INTERACTIVE_DIAGRAM }
enum class MediaApprovalStatus { EXTERNAL_CANDIDATE, RIGHTS_REVIEW_REQUIRED }

data class ScienceMediaResource(
    val id: String,
    val title: String,
    val subjectCode: String,
    val topicId: String,
    val mediaType: ScienceMediaType,
    val provider: String,
    val summary: String,
    val sourceUrl: String,
    val licenceName: String,
    val licenceUrl: String,
    val permittedUse: String,
    val beforeYouStart: String,
    val afterYouExplore: String,
    val offlineAlternative: String,
    val approvalStatus: MediaApprovalStatus = MediaApprovalStatus.EXTERNAL_CANDIDATE
) {
    val creatorOrPublisher: String
        get() = when (provider) {
            "PhET Interactive Simulations" -> "PhET Interactive Simulations, University of Colorado Boulder"
            "HHMI BioInteractive" -> "HHMI BioInteractive"
            "LabXchange" -> "The individual contributor named on the original LabXchange resource"
            else -> provider
        }

    val attributionText: String
        get() = when {
            provider == "PhET Interactive Simulations" -> "Simulation by PhET Interactive Simulations, University of Colorado Boulder, licensed under CC BY-NC 4.0 (https://phet.colorado.edu)."
            provider == "HHMI BioInteractive" -> "Credit HHMI BioInteractive and follow the resource-specific HHMI terms and attribution instructions."
            provider == "LabXchange" -> "Credit the individual creator shown on the original resource page; LabXchange is the hosting platform."
            provider.startsWith("Wikimedia Commons — ") -> "Credit ${provider.substringAfter("—").trim()} via Wikimedia Commons, link the original file page and the stated licence (${licenceName})."
            else -> "Credit the original creator and follow the source's current attribution instructions."
        }
}

